"""
ЗАДАЧА 2: РЕКОМЕНДАЦІЙНА СИСТЕМА НА ОСНОВІ КОСИНУСНОЇ ПОДІБНОСТІ

Опис:
------
Створюємо систему рекомендацій фільмів на основі профілю користувача.
Використовуємо косинусну подібність (cosine similarity) - метрику,
що вимірює подібність між векторами за їхнім напрямком у просторі.

Математичні формули:
--------------------

1. КОСИНУСНА ПОДІБНІСТЬ:

   cos(θ) = (u · v) / (||u|| · ||v||)

   де:
   - u · v - скалярний добуток векторів
   - ||u|| - норма (довжина) вектора u
   - ||v|| - норма вектора v
   - θ - кут між векторами

2. СКАЛЯРНИЙ ДОБУТОК (DOT PRODUCT):

   u · v = u₁·v₁ + u₂·v₂ + ... + uₙ·vₙ

   Для n=3: u · v = u₁·v₁ + u₂·v₂ + u₃·v₃

   Приклад:
   u = [8, 2, 5]
   v = [9, 1, 2]
   u · v = 8·9 + 2·1 + 5·2 = 72 + 2 + 10 = 84

3. ЕВКЛІДОВА НОРМА (ДОВЖИНА ВЕКТОРА):

   ||u|| = √(u₁² + u₂² + ... + uₙ²)

   Для n=3: ||u|| = √(u₁² + u₂² + u₃²)

   Приклад:
   u = [8, 2, 5]
   ||u|| = √(8² + 2² + 5²) = √(64 + 4 + 25) = √93 ≈ 9.644

4. ПОВНА ФОРМУЛА:

   Для u = [8, 2, 5] та v = [9, 1, 2]:

   cos(θ) = (8·9 + 2·1 + 5·2) / (√(8²+2²+5²) · √(9²+1²+2²))
          = 84 / (√93 · √86)
          = 84 / (9.644 · 9.274)
          = 84 / 89.43
          ≈ 0.94

Інтерпретація:
--------------
- cos(θ) = 1:   Вектори ідентичні (θ = 0°)
- cos(θ) = 0:   Вектори ортогональні (θ = 90°)
- cos(θ) = -1:  Вектори протилежні (θ = 180°)

Для рекомендацій: чим ближче до 1, тим більша подібність!

Практичне застосування:
------------------------
- Netflix, YouTube рекомендації
- Пошукові системи (Google, Bing)
- Аналіз текстів (схожість документів)
- Системи фільтрації спаму
"""

import numpy as np


def cosine_similarity(u, v):
    """Косинусна подібність: cos(θ) = (u·v) / (||u||·||v||)"""
    return u @ v / (np.linalg.norm(u) * np.linalg.norm(v))


# Вихідні дані: [екшн, комедія, драма] - оцінки від 0 до 10
user_profile = np.array([8, 2, 5])
movies = {
    "Фільм A (Action Movie)": np.array([9, 1, 2]),
    "Фільм B (Comedy Movie)": np.array([1, 9, 8]),
    "Фільм C (Drama Movie)": np.array([7, 2, 6]),
}

print("Профіль користувача [Екшн, Комедія, Драма]:", user_profile)
print("\nФільми:")
for name, vector in movies.items():
    print(f"  {name}: {vector}")

# 1. Норма вектора користувача
norm_user = np.linalg.norm(user_profile)
print(f"\n1. Норма вектора користувача: ||u|| = {norm_user:.4f}")

# 2. Обчислення схожості з кожним фільмом
print("\n2. Схожість профілю з фільмами:")
similarities = {}
for name, vector in movies.items():
    sim = cosine_similarity(user_profile, vector)
    similarities[name] = sim
    print(f"  {name}: {sim:.4f}")

# 3. Визначення найкращого фільму
best_movie = max(similarities.items(), key=lambda x: x[1])[0]
print(f"\n3. Рекомендація: {best_movie}")
print(f"   Схожість: {similarities[best_movie]:.4f}")

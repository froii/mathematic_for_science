"""
ЗАДАЧА 4: ПРОГНОЗУВАННЯ НАВАНТАЖЕННЯ СЕРВЕРА (ЛІНІЙНА РЕГРЕСІЯ)

Опис:
------
Маємо дані про навантаження сервера за 5 годин.
Потрібно побудувати лінійну модель (тренд) та спрогнозувати
навантаження на наступну годину.

Це класична задача МЕТОДУ НАЙМЕНШИХ КВАДРАТІВ (МНК / Least Squares).

Математична модель:
-------------------

ЛІНІЙНА РЕГРЕСІЯ: y = k·t + b

де:
  y - навантаження (CPU load)
  t - час (година)
  k - кутовий коефіцієнт (швидкість зростання навантаження)
  b - вільний член (початкове навантаження при t=0)

Дані:
  t = [1, 2, 3, 4, 5]
  y = [22, 28, 37, 45, 53]

МЕТА: знайти k та b, які мінімізують помилку прогнозу.

МЕТОД НАЙМЕНШИХ КВАДРАТІВ (МНК):
---------------------------------

Ідея: мінімізувати суму квадратів відхилень

  S = Σ(yᵢ - (k·tᵢ + b))² → min

У МАТРИЧНІЙ ФОРМІ:

Шукаємо вектор коефіцієнтів θ = [k, b]ᵀ з рівняння:

  A·θ = y

де матриця A складається зі стовпців [t, 1]:

  ┌       ┐       ┌   ┐       ┌    ┐
  │ 1  1  │       │ k │       │ 22 │
  │ 2  1  │       │   │       │ 28 │
  │ 3  1  │   ·   │ b │   =   │ 37 │
  │ 4  1  │       │   │       │ 45 │
  │ 5  1  │       └   ┘       │ 53 │
  └       ┘         θ         └    ┘
      A                          y

ПРОБЛЕМА: A не квадратна (5×2), тому немає прямого розв'язку!

РОЗВ'ЯЗАННЯ через нормальні рівняння:

  AᵀA·θ = Aᵀy

  θ = (AᵀA)⁻¹·Aᵀy

Це дає найкращі коефіцієнти k та b у смислі МНК.

АНАЛІТИЧНІ ФОРМУЛИ:

Для AᵀA:
  ┌           ┐   ┌       ┐   ┌                ┐
  │ 1 2 3 4 5 │   │ 1  1  │   │ Σt²    Σt      │   ┌        ┐
  │           │   │ 2  1  │   │                │   │ 55  15 │
  │ 1 1 1 1 1 │ · │ 3  1  │ = │ Σt     n       │ = │ 15   5 │
  │           │   │ 4  1  │   │                │   └        ┘
  └           ┘   │ 5  1  │   └                ┘
                  └       ┘

  де: Σt² = 1²+2²+3²+4²+5² = 1+4+9+16+25 = 55
      Σt = 1+2+3+4+5 = 15
      n = 5

Для Aᵀy:
  ┌           ┐   ┌    ┐   ┌          ┐   ┌     ┐
  │ 1 2 3 4 5 │   │ 22 │   │ Σ(t·y)   │   │ 634 │
  │           │   │ 28 │   │          │   │     │
  │ 1 1 1 1 1 │ · │ 37 │ = │ Σy       │ = │ 185 │
  │           │   │ 45 │   │          │   │     │
  └           ┘   │ 53 │   └          ┘   └     ┘
                  └    ┘

  де: Σ(t·y) = 1·22 + 2·28 + 3·37 + 4·45 + 5·53
             = 22 + 56 + 111 + 180 + 265 = 634
      Σy = 22+28+37+45+53 = 185

Практичне застосування:
------------------------
- Прогнозування навантаження серверів
- Аналіз трендів у фінансах
- Машинне навчання (базовий метод)
- Планування потужностей
"""

import numpy as np

# Вихідні дані
t = np.array([1, 2, 3, 4, 5])  # час (години)
y = np.array([22, 28, 37, 45, 53])  # навантаження (CPU load)

print("Вихідні дані:")
print(f"  Час (t):           {t}")
print(f"  Навантаження (y):  {y}")

# 1. Формування матриці A = [t, 1]
A = np.column_stack([t, np.ones(len(t), dtype="int")])
print("\nМатриця A (для моделі y = k·t + b):")
print(A)

# 2. Знаходження коефіцієнтів методом найменших квадратів
k, b = np.linalg.lstsq(A, y, rcond=None)[0]
print("\nКоефіцієнти лінійної регресії:")
print(f"  k (нахил) = {k:.4f}")
print(f"  b (зсув)  = {b:.4f}")
print(f"\nРівняння тренду: y = {k:.2f}·t + {b:.2f}")

# 3. Прогноз на наступну годину
next_hour = t[-1] + 1
next_load = k * next_hour + b
print(f"\nПрогноз на {next_hour}-ту годину: {next_load:.2f}")

# 4. Альтернативний метод: нормальні рівняння AᵀA·θ = Aᵀy
print("\n--- Альтернативний метод (нормальні рівняння) ---")
ATA = A.T @ A
ATy = A.T @ y
k_alt, b_alt = np.linalg.solve(ATA, ATy)

print(f"Коефіцієнти: k = {k_alt:.4f}, b = {b_alt:.4f}")
print(f"Методи збігаються? {np.allclose([k, b], [k_alt, b_alt])} ✓")

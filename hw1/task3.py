"""
ЗАДАЧА 3: РОЗВ'ЯЗАННЯ СИСТЕМИ ЛІНІЙНИХ РІВНЯНЬ (ВИРОБНИЦТВО ДРОНІВ)

Опис:
------
Завод виробляє 3 типи дронів з обмеженими ресурсами.
Потрібно знайти, скільки дронів кожного типу можна зібрати.
Це класична задача лінійної алгебри: розв'язання системи лінійних рівнянь.

Умова задачі:
-------------
Типи дронів:
  1. Розвідник  - потребує: 4 мотори, 1 контролер, 1 акумулятор
  2. Камікадзе  - потребує: 4 мотори, 1 контролер, 2 акумулятори
  3. Вантажний  - потребує: 6 моторів, 2 контролери, 4 акумулятори

Наявні ресурси:
  - Моторів: 460 шт.
  - Контролерів: 130 шт.
  - Акумуляторів: 240 шт.

Математична модель:
-------------------

СИСТЕМА ЛІНІЙНИХ РІВНЯНЬ:
  4x₁ + 4x₂ + 6x₃ = 460   (рівняння для моторів)
  1x₁ + 1x₂ + 2x₃ = 130   (рівняння для контролерів)
  1x₁ + 2x₂ + 4x₃ = 240   (рівняння для акумуляторів)

де:
  x₁ - кількість розвідників
  x₂ - кількість камікадзе
  x₃ - кількість вантажних

У МАТРИЧНІЙ ФОРМІ: A·x = b
  ┌           ┐   ┌    ┐   ┌     ┐
  │ 4  4  6   │   │ x₁ │   │ 460 │
  │ 1  1  2   │ · │ x₂ │ = │ 130 │
  │ 1  2  4   │   │ x₃ │   │ 240 │
  └           ┘   └    ┘   └     ┘
      A            x        b

МЕТОДИ РОЗВ'ЯЗАННЯ:
1. Правило Крамера (використовує визначники)
2. Метод Гауса (приведення до трикутного вигляду)
3. Обернена матриця: x = A⁻¹·b
4. NumPy np.linalg.solve() - використовує LU-розклад (найефективніший)

УМОВА ІСНУВАННЯ РОЗВ'ЯЗКУ:
  det(A) ≠ 0  →  система має єдиний розв'язок
  det(A) = 0  →  або немає розв'язку, або нескінченно багато

ОБЧИСЛЕННЯ ВИЗНАЧНИКА 3×3 (правило Саррюса):
  det(A) = a₁₁(a₂₂a₃₃ - a₂₃a₃₂) - a₁₂(a₂₁a₃₃ - a₂₃a₃₁) + a₁₃(a₂₁a₃₂ - a₂₂a₃₁)

Для нашої матриці:
  ┌           ┐
  │ 4  4  6   │
  │ 1  1  2   │
  │ 1  2  4   │
  └           ┘

  det(A) = 4·(1·4 - 2·2) - 4·(1·4 - 2·1) + 6·(1·2 - 1·1)
         = 4·(4 - 4) - 4·(4 - 2) + 6·(2 - 1)
         = 4·0 - 4·2 + 6·1
         = 0 - 8 + 6
         = -2

Практичне застосування:
------------------------
- Планування виробництва
- Оптимізація ресурсів
- Логістика та поставки
- Фінансове моделювання
"""

import numpy as np

# 1. Формування матриці коефіцієнтів A та вектора b
A = np.array(
    [
        [4, 4, 6],  # мотори
        [1, 1, 2],  # контролери
        [1, 2, 4],  # акумулятори
    ]
)
b = np.array([460, 130, 240])

print("Матриця коефіцієнтів A:")
print(A)
print("\nВектор вільних членів b:", b)

# 2. Перевірка існування розв'язку через визначник
det_A = round(np.linalg.det(A))
print(f"\nВизначник det(A) = {det_A}")

if det_A != 0:
    print("✓ Визначник НЕ дорівнює нулю → система має ЄДИНИЙ розв'язок")
else:
    print("✗ Визначник дорівнює нулю → система НЕ має єдиного розв'язку")
    exit()

# 3. Розв'язання системи: A·x = b
x = np.linalg.solve(A, b).astype(int)
print(f"\nРозв'язок x = {x}")
print("\nКількість дронів:")
print(f"  Розвідник  (x₁) = {x[0]} шт.")
print(f"  Камікадзе  (x₂) = {x[1]} шт.")
print(f"  Вантажний  (x₃) = {x[2]} шт.")

# 4. Перевірка: A·x = b
b_check = A @ x
print("\nПеревірка:")
print(f"  A·x = {b_check}")
print(f"  b   = {b}")
print(f"  A·x = b? {np.allclose(b_check, b)} ✓")
